function prefersReducedMotion() {
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}

function scrollPageTop() {
  window.scrollTo({ top: 0, behavior: prefersReducedMotion() ? "auto" : "smooth" });
}

function showView(html, viewId) {
  if (isTransitioning) return;
  currentView = viewId;

  if (!app.firstElementChild || prefersReducedMotion()) {
    app.innerHTML = html;
    bindViewEvents();
    scrollPageTop();
    return;
  }

  isTransitioning = true;
  const current = app.firstElementChild;
  current.classList.add("is-leaving");

  window.setTimeout(() => {
    app.innerHTML = html;
    const next = app.firstElementChild;
    if (next) next.classList.add("is-entering");
    bindViewEvents();
    isTransitioning = false;
    scrollPageTop();
  }, 260);
}

function openLightbox(src, alt) {
  if (!lightbox || !lightboxImg || !src) return;
  lightboxImg.src = src;
  lightboxImg.alt = alt || "";
  lightbox.hidden = false;
  document.body.classList.add("lightbox-open");
  lightboxClose?.focus();
}

function closeLightbox() {
  if (!lightbox || lightbox.hidden) return;
  lightbox.hidden = true;
  document.body.classList.remove("lightbox-open");
  if (lightboxImg) {
    lightboxImg.removeAttribute("src");
    lightboxImg.alt = "";
  }
}

function bindViewEvents() {
  app.querySelectorAll("[data-open-sister]").forEach((button) => {
    button.addEventListener("click", () => {
      const id = button.getAttribute("data-open-sister");
      openSister(id);
    });
  });

  const back = app.querySelector("[data-back-home]");
  if (back) {
    back.addEventListener("click", () => openHome());
  }

  app.querySelectorAll("[data-zoom-src]").forEach((el) => {
    const open = () =>
      openLightbox(el.getAttribute("data-zoom-src"), el.getAttribute("data-zoom-alt"));
    el.addEventListener("click", open);
    el.addEventListener("keydown", (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        open();
      }
    });
  });
}

function openHome() {
  history.pushState({ view: "home" }, "", "#home");
  document.title = HOME_TITLE;
  document.documentElement.style.setProperty("--accent", "#8f6a66");
  showView(renderHome(), "home");
}

function openSister(id) {
  const sister = sisters.find((item) => item.id === id);
  if (!sister) return;

  history.pushState({ view: "sister", id: sister.id }, "", `#${sister.id}`);
  document.title = `${sister.name} · ${HOME_TITLE}`;
  document.documentElement.style.setProperty("--accent", sister.color);
  showView(renderProfile(sister), sister.id);
}

function routeFromHash() {
  const hash = (location.hash || "#home").replace("#", "").toLowerCase();
  if (hash === "home" || hash === "") {
    document.title = HOME_TITLE;
    document.documentElement.style.setProperty("--accent", "#8f6a66");
    showView(renderHome(), "home");
    return;
  }

  const sister = sisters.find((item) => item.id === hash);
  if (sister) {
    document.title = `${sister.name} · ${HOME_TITLE}`;
    document.documentElement.style.setProperty("--accent", sister.color);
    showView(renderProfile(sister), sister.id);
    return;
  }

  openHome();
}

function createFloaters() {
  if (floaters) floaters.innerHTML = "";
}

window.addEventListener("popstate", () => {
  closeLightbox();
  routeFromHash();
});

function isMusicMutedStored() {
  try {
    return localStorage.getItem(musicConfig.storageKey) === "1";
  } catch {
    return false;
  }
}

function setMusicMutedStored(muted) {
  try {
    localStorage.setItem(musicConfig.storageKey, muted ? "1" : "0");
  } catch {
    /* ignore private mode */
  }
}

function updateMusicToggleUi(isPlaying) {
  if (!musicToggle) return;
  musicToggle.classList.toggle("is-playing", isPlaying);
  musicToggle.classList.toggle("is-muted", !isPlaying);
  musicToggle.setAttribute("aria-pressed", isPlaying ? "true" : "false");
  musicToggle.setAttribute(
    "aria-label",
    isPlaying ? "ปิดเสียงเพลง" : "เปิดเสียงเพลง"
  );
  musicToggle.title = isPlaying ? "ปิดเสียง" : "เปิดเสียง";
}

async function playMusic() {
  if (!audioEl || !userWantsMusic) return false;
  try {
    audioEl.volume = musicConfig.volume;
    await audioEl.play();
    updateMusicToggleUi(true);
    return true;
  } catch {
    updateMusicToggleUi(false);
    return false;
  }
}

function pauseMusic() {
  if (!audioEl) return;
  audioEl.pause();
  updateMusicToggleUi(false);
}

function finishUnlock() {
  if (musicGate) {
    musicGate.classList.remove("is-leaving");
    musicGate.hidden = true;
  }
  document.body.classList.add("is-unlocked");
}

function wait(ms) {
  return new Promise((resolve) => window.setTimeout(resolve, ms));
}

async function unlockMusicFromGesture() {
  if (musicReady) return;
  musicReady = true;

  const card = musicGateBtn;

  if (isMusicMutedStored()) {
    userWantsMusic = false;
    pauseMusic();
  } else {
    userWantsMusic = true;
    playMusic();
  }

  if (musicGate && card) {
    card.classList.remove("is-opening");
    void card.offsetWidth;
    card.classList.add("is-opening");

    await wait(prefersReducedMotion() ? 450 : 850);
    musicGate.classList.add("is-leaving");
    await wait(prefersReducedMotion() ? 280 : 650);
  }

  finishUnlock();
}

function setupLightbox() {
  if (!lightbox) return;

  lightboxClose?.addEventListener("click", closeLightbox);
  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) closeLightbox();
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeLightbox();
  });
}

function setupMusic() {
  if (!audioEl) return;

  if (musicConfig.src && audioEl.getAttribute("src") !== musicConfig.src) {
    audioEl.src = musicConfig.src;
  }
  audioEl.loop = true;
  audioEl.preload = "auto";
  audioEl.volume = musicConfig.volume;

  if (isMusicMutedStored()) {
    userWantsMusic = false;
    updateMusicToggleUi(false);
  } else {
    updateMusicToggleUi(false);
  }

  if (musicGate) {
    musicGate.hidden = false;
  }

  if (musicGateBtn) {
    musicGateBtn.addEventListener("click", () => {
      unlockMusicFromGesture();
    });
  }

  if (musicToggle) {
    musicToggle.addEventListener("click", async () => {
      if (!musicReady) {
        userWantsMusic = true;
        setMusicMutedStored(false);
        await unlockMusicFromGesture();
        return;
      }

      if (!audioEl.paused) {
        userWantsMusic = false;
        setMusicMutedStored(true);
        pauseMusic();
        return;
      }

      userWantsMusic = true;
      setMusicMutedStored(false);
      await playMusic();
    });
  }

  document.addEventListener("visibilitychange", () => {
    if (document.hidden) return;
    if (musicReady && userWantsMusic && audioEl.paused) {
      playMusic();
    }
  });
}

createFloaters();
setupLightbox();
setupMusic();
routeFromHash();
